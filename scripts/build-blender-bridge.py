"""Build the original Zaalis extension deterministically (Python stdlib only)."""
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'native/blender/zaalis_bridge'
VERSION = '1.0.1'
target = SOURCE.parent / f'zaalis-bridge-{VERSION}.zip'
with zipfile.ZipFile(target, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for name in ('__init__.py', 'blender_manifest.toml', 'LICENSE', 'COPYING'):
        info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        archive.writestr(info, (SOURCE / name).read_bytes())
release = dict(id='zaalis_bridge', version=VERSION, file=target.name,
               sha256=hashlib.sha256(target.read_bytes()).hexdigest())
(ROOT / 'src/integrations/blender-bridge-release.js').write_text(
    "'use strict';\n// Generated by scripts/build-blender-bridge.py; do not edit.\nmodule.exports = "
    + json.dumps(release, indent=2) + ';\n', encoding='utf8')
print(json.dumps(release))
